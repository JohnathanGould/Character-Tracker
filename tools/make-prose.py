#!/usr/bin/env python3
"""Rebuild sheet-prose.js (the static text sections of the Sheet tab) from the printed character sheet.
Usage: python3 tools/make-prose.py path/to/daerlieth_sheet.txt > sheet-prose.js
Sections are cut between marker lines, so the text sheet can change length without breaking this."""
import sys, json, html, re

lines = open(sys.argv[1], encoding="utf-8").read().split("\n")

def find(prefix, start=0):
    for i in range(start, len(lines)):
        if lines[i].lstrip().startswith(prefix):
            return i
    raise SystemExit("marker not found: " + prefix)

def cut(a, b, skip_first=False):
    i = find(a)
    j = find(b, i + 1) if b else len(lines)
    seg = lines[i + (1 if skip_first else 0):j]
    return seg

def to_html(seg):
    out, ul = [], False
    for ln in seg:
        t = ln.rstrip()
        if not t.strip() or re.match(r"^\s*[-=]{5,}\s*$", t):
            continue
        m = re.match(r"^\s*- (.*)$", t)
        if m:
            if not ul:
                out.append("<ul>"); ul = True
            out.append("<li>" + html.escape(m.group(1)) + "</li>")
            continue
        if ul:
            out.append("</ul>"); ul = False
        s = t.strip()
        if re.match(r"^[A-Z][A-Z /&'()0-9,:-]{6,}:?$", s):
            out.append("<h4>" + html.escape(s) + "</h4>")
        else:
            out.append("<p>" + html.escape(s) + "</p>")
    if ul:
        out.append("</ul>")
    return "".join(out)

P = {}
P["feats"] = to_html(cut("Racial (Moon elf", "Spell-less Ranger 8"))
P["ranger"] = to_html(cut("Spell-less Ranger 8", "Animal companion:"))
P["mage"] = to_html(cut("Eternal Mage 8 (Artillery", "Mythic: Archmage"))
P["mythic"] = to_html(cut("Mythic: Archmage", "SPELLBOOK"))
P["spells"] = to_html(cut("(D) = a spell", "SPELLS PER DAY")) + to_html(cut("Eldritch burnout:", "DAILY RESOURCES"))
P["daily"] = to_html(cut("DAILY RESOURCES", "SKILLS (Max", True))
P["gear"] = to_html(cut("MONEY:", "DESCRIPTION"))
P["lang"] = to_html(cut("Favored bonuses not included", "MONEY:"))
P["bg"] = to_html(cut("DESCRIPTION", "STILL NEEDS GM", True))
P["gm"] = to_html(cut("STILL NEEDS GM", "NOTES FOR PLAYER", True))
print("/* Generated by tools/make-prose.py from the printed character sheet. Do not edit by hand. */")
print("(function(){var E=window.SheetEngine||(window.SheetEngine={});E.PROSE=" + json.dumps(P, ensure_ascii=False) + ";})();")
